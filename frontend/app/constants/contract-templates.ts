export function applyTemplate(
  template: string,
  vars: {
    clientName?: string;
    projectTitle?: string;
    totalAmount?: number;
    startDate?: string;
    endDate?: string;
  },
): string {
  return template
    .replace(/{CLIENT_NAME}/g, vars.clientName ?? '(클라이언트명)')
    .replace(/{PROJECT_TITLE}/g, vars.projectTitle ?? '(프로젝트명)')
    .replace(
      /{TOTAL_AMOUNT}/g,
      vars.totalAmount ? vars.totalAmount.toLocaleString() : '0',
    )
    .replace(/{START_DATE}/g, vars.startDate ?? '(시작일)')
    .replace(/{END_DATE}/g, vars.endDate ?? '(종료일)');
}
